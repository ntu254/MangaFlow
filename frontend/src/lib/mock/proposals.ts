export const SAMPLE_MANUSCRIPT_URL = "https://example.com/sample-manuscript.pdf";
export const SAMPLE_REFERENCE_URL = "https://example.com/sample-reference.pdf";

function mkManuscript(
  proposalId: string,
  version: number,
  hoursAgo: number,
  note?: string,
  supersedes?: string,
): ManuscriptVersion {
  return {
    id: `${proposalId}-mv${version}`,
    version,
    fileName: `${proposalId}-v${version}.pdf`,
    fileUrl: SAMPLE_MANUSCRIPT_URL,
    fileType: "application/pdf",
    sizeKB: 1024 + version * 128,
    pageCount: 24 + version * 4,
    uploadedById: "u-mangaka",
    uploadedByName: "Inoue Takehiko",
    uploadedAt: ago(hoursAgo),
    note,
    supersedes,
  };
}

function mkMaterial(
  proposalId: string,
  kind: SupportingMaterial["kind"],
  title: string,
  hoursAgo: number,
): SupportingMaterial {
  return {
    id: `${proposalId}-mat-${kind}-${hoursAgo}`,
    kind,
    title,
    fileName: `${proposalId}-${kind}.pdf`,
    fileUrl: SAMPLE_REFERENCE_URL,
    fileType: "application/pdf",
    sizeKB: 512,
    uploadedAt: ago(hoursAgo),
  };
}

type SeedInput = Omit<
  SeriesProposal,
  "manuscripts" | "materials" | "requestedChanges" | "revisionRound"
> & {
  manuscripts?: ManuscriptVersion[];
  materials?: SupportingMaterial[];
  requestedChanges?: RequestedChange[];
  revisionRound?: number;
};

function seed(p: SeedInput): SeriesProposal {
  return {
    manuscripts: p.manuscripts ?? [],
    materials: p.materials ?? [],
    requestedChanges: p.requestedChanges ?? [],
    revisionRound: p.revisionRound ?? 0,
    ...p,
  };
}

